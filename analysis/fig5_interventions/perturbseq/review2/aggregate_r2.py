import json, os, sys, numpy as np
sys.path.insert(0, f"{_CMC_ROOT}/analysis/fig5_interventions/perturbseq")
from scipy.stats import wilcoxon, ttest_1samp
from statsmodels.stats.multitest import multipletests

R2 = f"{_CMC_RESULTS}/paper/analyses/review2/perturbseq"
R1 = f"{_CMC_RESULTS}/paper/analyses/perturbseq/runs"
LINES = ["jurkat", "k562"]; SEEDS = [42, 1, 2]; SIZES = ["5", "25", "100", "400"]
M2 = ["rr_pe_cent", "rr_retrieval"]
def J(f):
    try: return json.load(open(f))
    except Exception: return None

# ---- identical to aggregate_rev.seed_contrast / bh
def kovec(rows, m):
    return {r["gene"]: r.get(m) for r in rows if r.get(m) is not None and np.isfinite(r.get(m))}
def seed_contrast(ra_s, rb_s, m, nb=4000):
    rng = np.random.RandomState(0)
    seeds = [s for s in ra_s if s in rb_s]; genes = None; per = {}; Dmat = []
    for s in seeds:
        a, b = kovec(ra_s[s], m), kovec(rb_s[s], m); g = sorted(set(a) & set(b)); genes = g if genes is None else sorted(set(genes) & set(g))
    for s in seeds:
        a, b = kovec(ra_s[s], m), kovec(rb_s[s], m); d = np.array([b[g] - a[g] for g in genes]); Dmat.append(d)
        per[s] = dict(mean_a=float(np.mean([a[g] for g in genes])), mean_b=float(np.mean([b[g] for g in genes])), mean_diff=float(d.mean()),
                      p_wilcoxon=float(wilcoxon(d).pvalue) if np.any(d != 0) else 1.0)
    Dmat = np.array(Dmat); n = Dmat.shape[1]; dbar = Dmat.mean(0)
    bs = dbar[rng.randint(0, n, (nb, n))].mean(1)
    hb = np.array([Dmat[rng.randint(0, len(seeds), len(seeds))][:, rng.randint(0, n, n)].mean() for _ in range(1000)])
    sd = Dmat.mean(1)
    return dict(n_ko=n, n_seeds=len(seeds), mean_a=float(np.mean([v["mean_a"] for v in per.values()])), mean_b=float(np.mean([v["mean_b"] for v in per.values()])),
                mean_diff=float(dbar.mean()), ci95_ko=[float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))],
                ci95_hier=[float(np.percentile(hb, 2.5)), float(np.percentile(hb, 97.5))],
                p_wilcoxon_seedavg=float(wilcoxon(dbar).pvalue) if np.any(dbar != 0) else 1.0,
                seed_diffs=[float(x) for x in sd], sign_consistent=bool(np.all(sd > 0) or np.all(sd < 0)),
                p_t_seedlevel=float(ttest_1samp(sd, 0).pvalue) if len(sd) > 1 and np.std(sd) > 0 else None,
                max_p_per_seed=float(max(v["p_wilcoxon"] for v in per.values())))
def bh(panel):
    ks = [k for k in panel if "p_wilcoxon_seedavg" in panel[k]]
    if ks:
        q = multipletests([panel[k]["p_wilcoxon_seedavg"] for k in ks], method="fdr_bh")[1]
        for k, v in zip(ks, q): panel[k]["q_bh"] = float(v)
    return panel

def mean_sd(vals):
    v = [x for x in vals if x is not None]
    return dict(mean=float(np.mean(v)) if v else None, sd=float(np.std(v, ddof=1)) if len(v) > 1 else None, per_seed=vals)

OUT = dict(plan="PLAN.md", lc={}, lc_contrasts={}, lc_alpha_robustness={}, um={}, um_contrasts={}, repro={})
md = ["# Review-2 Perturb-seq tables (auto-generated by code/aggregate_r2.py)"]
f3 = lambda x: "-" if x is None else f"{x:+.3f}"; pf = lambda p: "-" if p is None else f"{p:.1g}"

for line in LINES:
    old = {s: J(f"{R1}/{line}_obs_s{s}.json") for s in SEEDS}          # published full-data runs (ft, nb)
    oldlc = {s: J(f"{R1}/{line}_obs_s{s}_lc.json") for s in SEEDS}
    lc2 = {s: (J(f"{R2}/runs/{line}_obs_s{s}_lc2.json") or {}).get("lc2") for s in SEEDS}
    um = {s: (J(f"{R2}/runs/{line}_obs_s{s}_um.json") or {}).get("um") for s in SEEDS}
    lc2 = {s: v for s, v in lc2.items() if v}; um = {s: v for s, v in um.items() if v}

    # ---------------- full-data rows per arm (per seed)
    full = {}
    for s in SEEDS:
        F = old[s]["ft"]["shift"]; full.setdefault("scm_real", {})[s] = F["real"]["per_ko"]; full.setdefault("scm_shuffle", {})[s] = F["shuffle_avg"]["per_ko"]
        full.setdefault("scm_infonce", {})[s] = F["infonce"]["per_ko"]; full.setdefault("scm_infonce_shuffle", {})[s] = F["infonce_shuffle_avg"]["per_ko"]
        full.setdefault("obs", {})[s] = old[s]["obs"]["cmc_shift"]["per_ko"]
        for k in ["ridge_footprint", "ridge_ntcorr", "rrr_spanD_r192"]: full.setdefault(k, {})[s] = old[s]["nb"][k]["per_ko"]
        if s in um:
            for k, k2 in [("um_real", "um_real"), ("um_shuffle", "um_shuffle_avg"), ("um_infonce", "um_infonce"), ("um_infonce_shuffle", "um_infonce_shuffle_avg"),
                          ("um_real_lrsel", "um_real_lrsel"), ("scm_real_rerun", "scm_real_rerun"), ("scm_real_lrsel", "scm_real_lrsel")]:
                if k2 in um[s]: full.setdefault(k, {})[s] = um[s][k2]["per_ko"]

    # ---------------- Task 1: learning curve table
    ARMS = ["scm_real", "scm_infonce", "scm_shuffle", "scm_infonce_shuffle", "um_real", "um_infonce", "um_shuffle", "um_infonce_shuffle",
            "ridge_footprint", "ridge_ntcorr", "rrr_spanD_r192"]
    tab = {}
    for n in SIZES + ["all"]:
        tab[n] = {}
        for a in ARMS:
            if n == "all":
                rows = full.get(a, {})
                vals = {m: [float(np.nanmean([r[m] for r in rows[s]])) if s in rows else None for s in SEEDS] for m in M2}
            else:
                vals = {m: [lc2[s][n][a]["mean"][m] if s in lc2 and n in lc2[s] and a in lc2[s][n] else None for s in SEEDS] for m in M2}
            tab[n][a] = {m: mean_sd(vals[m]) for m in M2}
    OUT["lc"][line] = tab
    md.append(f"\n## Task 1 — learning curve, {line} (obs pretraining; mean ± s.d. across 3 seed models of the per-model subset means; 'all' = published full-data runs + new UM full-data runs)")
    for m in M2:
        md.append(f"\n**{m}**\n\n| n | " + " | ".join(ARMS) + " |\n|" + "---|" * (len(ARMS) + 1))
        for n in SIZES + ["all"]:
            md.append(f"| {n} | " + " | ".join("-" if tab[n][a][m]["mean"] is None else f"{tab[n][a][m]['mean']:.3f}±{(tab[n][a][m]['sd'] or 0):.3f}" for a in ARMS) + " |")

    # ---------------- Task 1 contrasts (b - a)
    CON = [("ridge_footprint", "scm_real"), ("ridge_footprint", "scm_infonce"), ("ridge_ntcorr", "scm_real"), ("rrr_spanD_r192", "scm_real"),
           ("scm_shuffle", "scm_real"), ("scm_infonce_shuffle", "scm_infonce"), ("um_real", "scm_real"), ("um_infonce", "scm_infonce"),
           ("um_shuffle", "um_real"), ("um_infonce_shuffle", "um_infonce"), ("ridge_footprint", "um_real")]
    OUT["lc_contrasts"][line] = {}
    md.append(f"\nContrasts {line} (b − a; seed-averaged per-KO two-sided Wilcoxon, BH within (line, n) panel; hierarchical bootstrap CI seeds→KOs)\n\n"
              "| n | b vs a | metric | mean a | mean b | Δ | 95% CI (hier.) | per-seed Δ | P | q BH |\n|---|---|---|---|---|---|---|---|---|---|")
    for n in SIZES + ["all"]:
        panel = {}
        for a, b in CON:
            if n == "all": ra, rb = full.get(a, {}), full.get(b, {})
            else:
                ra = {s: lc2[s][n][a]["per_ko_avg"] for s in lc2 if a in lc2[s].get(n, {})}; rb = {s: lc2[s][n][b]["per_ko_avg"] for s in lc2 if b in lc2[s].get(n, {})}
            if len(set(ra) & set(rb)) < 2: continue
            for m in M2: panel[f"{b}_vs_{a}|{m}"] = seed_contrast(ra, rb, m)
        bh(panel); OUT["lc_contrasts"][line][n] = panel
        for k, v in panel.items():
            c, m = k.split("|")
            md.append(f"| {n} | {c} | {m.replace('rr_','')} | {v['mean_a']:.3f} | {v['mean_b']:.3f} | {v['mean_diff']:+.3f} | [{v['ci95_hier'][0]:+.3f}, {v['ci95_hier'][1]:+.3f}] | "
                      f"{', '.join(f'{x:+.3f}' for x in v['seed_diffs'])} | {pf(v['p_wilcoxon_seedavg'])} | {pf(v.get('q_bh'))} |")

    # ---------------- alpha robustness at n=5/25
    ar = {}
    for n in ["5", "25"]:
        ks = sorted({k for s in lc2 for k in lc2[s].get(n, {}) if k.startswith("ridge_footprint_a")}, key=lambda k: float(k[len("ridge_footprint_a"):]))
        ar[n] = {k: {m: mean_sd([lc2[s][n][k]["mean"][m] if s in lc2 and k in lc2[s].get(n, {}) else None for s in SEEDS])["mean"] for m in M2} for k in ks}
        sel = [lc2[s][n]["ridge_footprint"]["info"] for s in lc2 if n in lc2[s]]
        ar[n]["selected_alphas"] = [i["alpha"] for x in sel for i in x]
    OUT["lc_alpha_robustness"][line] = ar
    md.append(f"\nRidge-on-decoder-loadings at every fixed alpha, {line} (seed mean of subset means) vs SCM FT")
    for n in ["5", "25"]:
        if not ar[n]: continue
        md.append(f"\n n={n}: selected alphas (all subsets × seeds) = {ar[n]['selected_alphas']}\n\n| alpha | pe_cent | retrieval |\n|---|---|---|")
        for k, v in ar[n].items():
            if k != "selected_alphas": md.append(f"| {k[len('ridge_footprint_a'):]} | {f3(v['rr_pe_cent'])} | {f3(v['rr_retrieval'])} |")

    # ---------------- reproducibility vs the published lc / ft
    rep = {}
    for s in lc2:
        for n in ["25", "100", "400"]:
            for a, ao in [("scm_real", "real"), ("scm_shuffle", "shuffle"), ("ridge_footprint", "ridge_footprint"), ("rrr_spanD_r192", "rrr_spanD_r192")]:
                if oldlc[s] and n in lc2[s] and a in lc2[s][n]:
                    x = np.array(lc2[s][n][a]["per_subset"]["rr_pe_cent"], float); y = np.array(oldlc[s]["lc"]["shift"][n][ao]["per_subset"]["rr_pe_cent"], float)
                    rep[f"s{s}_n{n}_{a}"] = float(np.nanmax(np.abs(x - y)))
        if "5" in lc2[s] and oldlc[s]:
            x = np.array(lc2[s]["5"]["ridge_footprint"]["per_subset"]["rr_pe_cent"], float); y = np.array(oldlc[s]["lc"]["shift"]["5"]["ridge_footprint"]["per_subset"]["rr_pe_cent"], float)
            rep[f"s{s}_n5_ridge_footprint"] = float(np.nanmax(np.abs(x - y)))
    for s in um:
        if "scm_real_rerun" in um[s]:
            a = kovec(um[s]["scm_real_rerun"]["per_ko"], "rr_pe_cent"); b = kovec(old[s]["ft"]["shift"]["real"]["per_ko"], "rr_pe_cent")
            rep[f"s{s}_full_scm_real_rerun"] = float(max(abs(a[g] - b[g]) for g in a if g in b))
    OUT["repro"][line] = dict(max_abs_diff_pe_cent=rep, max=max(rep.values()) if rep else None)

    # ---------------- Task 2: full-data UM vs SCM
    if um:
        uarms = ["obs", "scm_real", "scm_real_rerun", "um_real", "scm_real_lrsel", "um_real_lrsel", "scm_shuffle", "um_shuffle", "scm_infonce", "um_infonce", "scm_infonce_shuffle", "um_infonce_shuffle"]
        ut = {a: {m: mean_sd([float(np.nanmean([r[m] for r in full[a][s]])) if s in full.get(a, {}) else None for s in SEEDS]) for m in M2} for a in uarms if a in full}
        info = {s: {k: um[s][k].get("info") for k in um[s] if um[s][k].get("info") is not None} for s in um}
        OUT["um"][line] = dict(arms=ut, info=info)
        md.append(f"\n## Task 2 — unstructured latent map vs SCM, {line}, full training set (mean ± s.d. over seeds)\n\n| arm | centred pearDE | retrieval |\n|---|---|---|")
        for a in ut: md.append(f"| {a} | {ut[a]['rr_pe_cent']['mean']:.3f} ± {(ut[a]['rr_pe_cent']['sd'] or 0):.3f} | {ut[a]['rr_retrieval']['mean']:.3f} ± {(ut[a]['rr_retrieval']['sd'] or 0):.3f} |")
        md.append("\nUM fit info per seed: " + "; ".join(f"s{s}: real steps {info[s]['um_real']['n_steps']} relΔM {info[s]['um_real']['rel_change_M']:.3f}, infonce λ "
                                                       f"{[g['lam'] for g in [max(info[s]['um_infonce']['inner_grid'].values(), key=lambda v: v['inner_retr'])]][0]} steps {info[s]['um_infonce']['n_steps']}, "
                                                       f"lrsel lr {info[s].get('um_real_lrsel', {}).get('lr')}" for s in info))
        panel = {}
        for a, b in [("um_real", "scm_real"), ("um_infonce", "scm_infonce"), ("scm_shuffle", "scm_real"), ("um_shuffle", "um_real"),
                     ("scm_infonce_shuffle", "scm_infonce"), ("um_infonce_shuffle", "um_infonce"), ("um_real_lrsel", "scm_real"), ("um_real_lrsel", "scm_real_lrsel"), ("obs", "um_real"), ("obs", "scm_real"),
                     ("um_real", "ridge_footprint")]:
            if a in full and b in full:
                for m in M2: panel[f"{b}_vs_{a}|{m}"] = seed_contrast(full[a], full[b], m)
        bh(panel); OUT["um_contrasts"][line] = panel
        md.append("\n| b vs a | metric | mean a | mean b | Δ | 95% CI (KO boot) | 95% CI (hier.) | per-seed Δ | P (seed-avg Wilcoxon) | q BH |\n|---|---|---|---|---|---|---|---|---|---|")
        for k, v in panel.items():
            c, m = k.split("|")
            md.append(f"| {c} | {m.replace('rr_','')} | {v['mean_a']:.3f} | {v['mean_b']:.3f} | {v['mean_diff']:+.3f} | [{v['ci95_ko'][0]:+.3f}, {v['ci95_ko'][1]:+.3f}] | "
                      f"[{v['ci95_hier'][0]:+.3f}, {v['ci95_hier'][1]:+.3f}] | {', '.join(f'{x:+.3f}' for x in v['seed_diffs'])} | {pf(v['p_wilcoxon_seedavg'])} | {pf(v.get('q_bh'))} |")

json.dump(OUT, open(f"{R2}/results.json", "w"), indent=1)
open(f"{R2}/tables_r2.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
